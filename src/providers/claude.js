// @ts-check
const os = require('os');
const path = require('path');
const fs = require('fs');
const { readJsonl, readHead, listFiles, mtime } = require('../core/util');

const projectsRoot = () =>
  path.join(process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude'), 'projects');

// Claude Code stores transcripts in ~/.claude/projects/<cwd with non-alphanumerics replaced by '-'>/
const encodeCwd = (cwd) => cwd.replace(/[^a-zA-Z0-9]/g, '-');

function projectDir(cwd) {
  const dir = path.join(projectsRoot(), encodeCwd(cwd));
  return fs.existsSync(dir) ? dir : null;
}

/**
 * True only for a .jsonl transcript directly inside Claude Code's folder for this project,
 * after resolving symlinks. Hook payloads name a transcript by path, and a file planted in
 * .carrycontext/inbox must not be able to point at another project's conversation.
 */
function isOwnTranscript(cwd, file) {
  try {
    const real = fs.realpathSync(file);
    if (!real.endsWith('.jsonl') || !fs.statSync(real).isFile()) return false;
    const dirs = [...new Set([cwd, fs.realpathSync(cwd)])]
      .map((c) => path.join(projectsRoot(), encodeCwd(c)))
      .filter((d) => fs.existsSync(d))
      .map((d) => fs.realpathSync(d));
    return dirs.includes(path.dirname(real));
  } catch {
    return false;
  }
}

// Harness noise that is not part of the real conversation.
const NOISE = /^(<command-|<local-command-|<system-reminder>|Caveat: The messages below)/;
// Context the IDE extension attaches to user prompts (opened file, selection, reminders).
const ATTACHED = /<(ide_[a-z_]+|system-reminder)>[\s\S]*?<\/\1>/g;

/** @type {import('./types').ProviderAdapter} */
module.exports = {
  id: 'claude',
  label: 'Claude Code',
  isOwnTranscript,

  async listSessions(cwd) {
    const dir = projectDir(cwd);
    if (!dir) return [];
    return listFiles(dir, (f) => f.endsWith('.jsonl'))
      .map((file) => ({
        provider: 'claude',
        id: path.basename(file, '.jsonl'),
        path: file,
        updatedAt: mtime(file),
        title: firstPrompt(file),
      }))
      .sort((a, b) => b.updatedAt - a.updatedAt);
  },

  async readSession(ref) {
    /** @type {import('./types').Message[]} */
    const out = [];
    let customTitle;
    let aiTitle;
    /** @type {Map<string, import('./types').ToolCall>} */
    const calls = new Map();
    for (const e of readJsonl(ref.path)) {
      // Session names: set by /rename (custom-title) or generated by Claude Code (ai-title).
      if (e.type === 'custom-title' && e.customTitle) customTitle = e.customTitle;
      if (e.type === 'ai-title' && e.aiTitle) aiTitle = e.aiTitle;
      if ((e.type !== 'user' && e.type !== 'assistant') || e.isMeta || e.isSidechain) continue;
      const msg = e.message;
      if (!msg) continue;
      const blocks = typeof msg.content === 'string' ? [{ type: 'text', text: msg.content }] : msg.content || [];
      const text = [];
      const tools = [];
      for (const b of blocks) {
        const clean = b.type === 'text' && b.text ? b.text.replace(ATTACHED, '').trim() : '';
        if (clean && !NOISE.test(clean)) text.push(clean);
        else if (b.type === 'tool_use') {
          const call = { name: b.name, input: b.input, id: b.id };
          calls.set(b.id, call);
          tools.push(call);
        } else if (b.type === 'tool_result') attachResult(calls.get(b.tool_use_id), b);
      }
      if (!text.length && !tools.length) continue;
      out.push({
        role: e.isCompactSummary ? 'system' : msg.role === 'assistant' ? 'assistant' : 'user',
        text: e.isCompactSummary ? `[Earlier compaction summary]\n${text.join('\n')}` : text.join('\n'),
        tools,
        ts: e.timestamp,
        provider: 'claude',
        branch: e.gitBranch || undefined,
      });
    }
    ref.title = customTitle || aiTitle || ref.title;
    return out;
  },

  target: {
    // Picked up by the SessionStart hook (see claudeHooks.js), so no instruction file edit is needed.
    handoffFile: (cwd) => path.join(cwd, '.claude', 'handoff.md'),
  },

  launch: {
    terminal: (prompt, quote) => `claude ${quote(prompt)}`,
  },
};

/** Record a tool_result on its call: failed results have is_error, shell ones start "Exit code N". */
function attachResult(call, result) {
  if (!call) return;
  call.ok = !result.is_error;
  const content = typeof result.content === 'string' ? result.content : (result.content || []).map((c) => c.text || '').join('\n');
  const exit = content.match(/^Exit code (\d+)/);
  if (exit) call.exitCode = Number(exit[1]);
  else if (call.ok && /^(Bash|shell)$/i.test(call.name)) call.exitCode = 0;
}

function firstPrompt(file) {
  // Cheap title: first real user text in the first 64 KB.
  const head = readHead(file, 65536);
  for (const line of head.split('\n')) {
    try {
      const e = JSON.parse(line);
      if (e.type !== 'user' || e.isMeta) continue;
      const c = e.message?.content;
      const text = typeof c === 'string' ? c : (c || []).find((b) => b.type === 'text')?.text;
      if (text && !NOISE.test(text.trim())) return text.replace(/\s+/g, ' ').slice(0, 80);
    } catch {
      // last line is usually cut off
    }
  }
  return undefined;
}
