// @ts-check
// Claude Code integration: hooks that refresh the handoff on compact / session end,
// inject it into new sessions, and the /compact-all slash command.
const fs = require('fs');
const path = require('path');
const { paths, updateHandoff, syncTargets } = require('./handoff');
const { writeFile, readJson, readText, listFiles, mtime, shellQuote } = require('./util');
const { excludeLocally } = require('./git');
const claude = require('../providers/claude');

const HOOK_MARK = '.carrycontext/hooks/claude-hook.sh';
const hookScriptPath = (cwd) => path.join(paths(cwd).dir, 'hooks', 'claude-hook.sh');
const settingsPath = (cwd) => path.join(cwd, '.claude', 'settings.local.json');

const hookCommand = (arg) => `sh "$CLAUDE_PROJECT_DIR/${HOOK_MARK}" ${arg}`;

const HOOKS = {
  PreCompact: { arg: 'update', timeout: 30 },
  SessionEnd: { arg: 'update', timeout: 30 },
  // Fresh sessions, and right after compaction so the summary doesn't lose the handoff.
  // A resumed session already has its context.
  SessionStart: { arg: 'session-start', timeout: 10, matcher: 'startup|clear|compact' },
};

/**
 * The hook script runs the CLI with whatever Node it can find: `node` on PATH, else
 * the Node runtime bundled in VS Code (ELECTRON_RUN_AS_NODE). If neither works, it
 * leaves the payload in .carrycontext/inbox for the extension to pick up later.
 */
function hookScript(cliPath, nodePath) {
  return `#!/bin/sh
# Generated by CarryContext. Rewritten each time the VS Code extension starts.
DIR="\${CLAUDE_PROJECT_DIR:-$(pwd)}"
CC="$DIR/.carrycontext"
CLI=${shellQuote(cliPath)}
VSCODE_NODE=${shellQuote(nodePath)}

run_cli() {
  if command -v node >/dev/null 2>&1 && [ -f "$CLI" ]; then
    node "$CLI" "$@" --cwd "$DIR"
  elif [ -x "$VSCODE_NODE" ] && [ -f "$CLI" ]; then
    ELECTRON_RUN_AS_NODE=1 "$VSCODE_NODE" "$CLI" "$@" --cwd "$DIR"
  else
    return 1
  fi
}

case "$1" in
  session-start)
    # Switch to the checked-out branch's handoff first. Without a Node runtime, read the
    # branch's file directly (same folder naming as branchSlug() in src/core/git.js).
    if run_cli activate >/dev/null 2>&1; then
      FILE="$DIR/.claude/handoff.md"
    else
      B=$(sed -n 's#^ref: refs/heads/##p' "$DIR/.git/HEAD" 2>/dev/null)
      SLUG=$(printf %s "$B" | sed 's#/#__#g; s#[^A-Za-z0-9._-]#-#g')
      FILE="$CC/branches/$SLUG/handoff.md"
      { [ -n "$B" ] && [ -f "$FILE" ]; } || FILE="$DIR/.claude/handoff.md"
    fi
    [ -f "$FILE" ] && cat "$FILE"
    exit 0 ;;
  sync)
    run_cli sync || { mkdir -p "$CC/inbox"; echo '{"command":"sync"}' > "$CC/inbox/sync-$(date +%s).json"; }
    exit 0 ;;
  update)
    mkdir -p "$CC/inbox"
    PAYLOAD="$CC/inbox/claude-$(date +%s)-$$.json"
    cat > "$PAYLOAD"
    run_cli hook claude --payload "$PAYLOAD" >>"$CC/hook.log" 2>&1
    exit 0 ;;
  cli)
    # Any CarryContext command, with whichever Node runtime is available (used by the start-story skill).
    shift
    run_cli "$@"
    exit $? ;;
esac
`;
}

/** Write the hook script, register hooks in .claude/settings.local.json, add /compact-all. */
function installClaudeHooks(cwd, cliPath, nodePath) {
  writeHookScript(cwd, cliPath, nodePath);

  updateHookSettings(cwd, true);

  const cmd = path.join(cwd, '.claude', 'commands', 'compact-all.md');
  // Refresh our own command file, but leave it alone if the user rewrote it.
  const current = readText(cmd);
  if (current == null || current.includes('so any assistant (Claude, Codex')) writeFile(cmd, COMPACT_ALL_COMMAND);

  // The start-story skill: Claude uses it when you say you're starting stories. Kept out of git.
  const skill = path.join(cwd, '.claude', 'skills', 'start-story', 'SKILL.md');
  const ours = readText(skill);
  if (ours == null || ours.includes(SKILL_MARK)) writeFile(skill, START_STORY_SKILL);
  excludeLocally(cwd, [skill]);
}

function writeHookScript(cwd, cliPath, nodePath) {
  const file = hookScriptPath(cwd);
  const content = hookScript(cliPath, nodePath);
  if (readText(file) !== content) {
    writeFile(file, content);
    fs.chmodSync(file, 0o755);
  }
}

/**
 * Add our hook entries, or bring existing ones up to date (matcher, command, timeout).
 * Only entries that run our hook script are touched.
 */
function updateHookSettings(cwd, addMissing) {
  const file = settingsPath(cwd);
  const before = readText(file);
  const settings = readJson(file, {});
  settings.hooks ||= {};
  for (const [event, { arg, timeout, matcher }] of Object.entries(HOOKS)) {
    if (!settings.hooks[event] && !addMissing) continue;
    const entries = (settings.hooks[event] ||= []);
    const wanted = { ...(matcher ? { matcher } : {}), hooks: [{ type: 'command', command: hookCommand(arg), timeout }] };
    const i = entries.findIndex((e) => (e.hooks || []).some((h) => String(h.command || '').includes(HOOK_MARK)));
    if (i >= 0) entries[i] = wanted;
    else if (addMissing) entries.push(wanted);
  }
  const after = JSON.stringify(settings, null, 2) + '\n';
  if (after !== before) writeFile(file, after);
}

function hooksInstalled(cwd) {
  return (readText(settingsPath(cwd)) || '').includes(HOOK_MARK);
}

const MAX_PAYLOAD_BYTES = 256 * 1024; // real hook payloads are a few hundred bytes

/**
 * Handle one hook payload from the inbox. Claims the file by renaming it so the CLI
 * and the extension never process the same payload twice. Payloads naming a transcript
 * outside this project's Claude folder are ignored.
 * @returns {Promise<{file: string, warning?: string} | {ignored: string} | null>}
 */
async function processPayload(cwd, payloadFile, config, getApiKey) {
  const claimed = `${payloadFile}.working`;
  try {
    fs.renameSync(payloadFile, claimed);
  } catch {
    return null; // someone else took it
  }
  try {
    if (fs.statSync(claimed).size > MAX_PAYLOAD_BYTES) return { ignored: 'payload is too large' };
    const payload = readJson(claimed, {});
    if (payload.command === 'sync') {
      syncTargets(cwd, config);
      return { file: paths(cwd).handoff };
    }
    const transcript = payload.transcript_path;
    if (typeof transcript !== 'string' || !fs.existsSync(transcript)) return null;
    if (!claude.isOwnTranscript(cwd, transcript)) return { ignored: "transcript is not in this project's Claude Code folder" };
    const ref = { provider: 'claude', id: payload.session_id || path.basename(transcript, '.jsonl'), path: transcript, updatedAt: mtime(transcript) };
    const detail = payload.trigger || payload.reason;
    const trigger = `claude:${payload.hook_event_name || 'hook'}${detail ? ':' + detail : ''}`;
    return await updateHandoff({ cwd, sessions: [{ adapter: claude, ref }], trigger, config, getApiKey });
  } finally {
    fs.rmSync(claimed, { force: true });
  }
}

/** Payloads left behind when no Node runtime was available to the hook. */
function pendingPayloads(cwd, minAgeMs = 0) {
  const now = Date.now();
  return listFiles(paths(cwd).inbox, (f) => f.endsWith('.json')).filter((f) => now - mtime(f) >= minAgeMs);
}

